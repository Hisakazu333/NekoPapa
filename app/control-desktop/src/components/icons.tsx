/** 今日学习列表行图标：词汇 / 听力 / 语法 / 默认（她的闪星） */
export function TodayIcon({ title, size = 14 }: { title: string; size?: number }) {
  const t = title || "";
  if (/词|单词|词汇/.test(t)) return <IconLib size={size} />;
  if (/听|听力/.test(t)) return <IconHeadphones size={size} />;
  if (/语法|句型/.test(t)) return <IconGrammar size={size} />;
  return <IconSparkleFill size={size} />;
}
